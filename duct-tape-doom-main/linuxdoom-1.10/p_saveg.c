//
// P_ArchiveThinkers
//
typedef struct { mobj_t *object; uintptr_t index; } saved_object_t;
static int compare_saved_objects(const void *a,const void *b)
{
    uintptr_t x=(uintptr_t)((const saved_object_t*)a)->object;
    uintptr_t y=(uintptr_t)((const saved_object_t*)b)->object;
    return (x>y)-(x<y);
}
static uintptr_t saved_object_index(saved_object_t *objects,size_t count,mobj_t *object)
{
    saved_object_t key,*found;
    if(!object||!count)return 0;
    key.object=object;key.index=0;
    found=bsearch(&key,objects,count,sizeof(*objects),compare_saved_objects);
    return found?found->index:0;
}
void P_ArchiveThinkers (void)
{
    thinker_t*		th;
    mobj_t*		mobj;
    size_t count=0,index=0;
    saved_object_t *objects;

    for(th=thinkercap.next;th!=&thinkercap;th=th->next)
        if(th->function.acp1==(actionf_p1)P_MobjThinker)++count;
    if(count>1000000)I_Error("Too many actors to save");
    objects=Z_Malloc((count?count:1)*sizeof(*objects),PU_STATIC,NULL);
    for(th=thinkercap.next;th!=&thinkercap;th=th->next)
        if(th->function.acp1==(actionf_p1)P_MobjThinker){objects[index].object=(mobj_t*)th;objects[index].index=index+1;++index;}
    qsort(objects,count,sizeof(*objects),compare_saved_objects);
	
    // save off the current thinkers
    for (th = thinkercap.next ; th != &thinkercap ; th=th->next)
    {
	if (th->function.acp1 == (actionf_p1)P_MobjThinker)
	{
	    *save_p++ = tc_mobj;
	    PADSAVEP();
	    mobj = (mobj_t *)save_p;
	    memcpy (mobj, th, sizeof(*mobj));
	    save_p += sizeof(*mobj);
	    mobj->state = (state_t *)(uintptr_t)(mobj->state - states);
        mobj->target=(mobj_t*)saved_object_index(objects,count,mobj->target);
        mobj->tracer=(mobj_t*)saved_object_index(objects,count,mobj->tracer);
	    
	    if (mobj->player)
		mobj->player = (player_t *)(uintptr_t)((mobj->player-players) + 1);
	    continue;
	}
		
	// I_Error ("P_ArchiveThinkers: Unknown thinker function");
    }

    // add a terminating marker
    *save_p++ = tc_end;	
    Z_Free(objects);
}



//
// P_UnArchiveThinkers
//
void P_UnArchiveThinkers (void)
{
    byte		tclass;
    thinker_t*		currentthinker;
    thinker_t*		next;
    mobj_t*		mobj;
    mobj_t **objects=NULL;
    size_t count=0,capacity=0,i;
    
    // remove all the current thinkers
    currentthinker = thinkercap.next;
    while (currentthinker != &thinkercap)
    {
	next = currentthinker->next;
	
	if (currentthinker->function.acp1 == (actionf_p1)P_MobjThinker)
	    P_RemoveMobj ((mobj_t *)currentthinker);
	else
	    Z_Free (currentthinker);

	currentthinker = next;
    }
    P_InitThinkers ();
	
    // read in saved thinkers
    while (1)
    {
	tclass = *save_p++;
	switch (tclass)
	{
	  case tc_end:
        // Resolve only after every actor exists. Legacy saves stored raw
        // addresses here; out-of-range values safely become null.
        for(i=0;i<count;++i){
            uintptr_t target=(uintptr_t)objects[i]->target,tracer=(uintptr_t)objects[i]->tracer;
            objects[i]->target=target&&target<=count?objects[target-1]:NULL;
            objects[i]->tracer=tracer&&tracer<=count?objects[tracer-1]:NULL;
        }
        free(objects);
	    return; 	// end of list
			
	  case tc_mobj:
	    PADSAVEP();
	    mobj = Z_Malloc (sizeof(*mobj), PU_LEVEL, NULL);
	    memcpy (mobj, save_p, sizeof(*mobj));
	    save_p += sizeof(*mobj);
	    mobj->state = &states[(uintptr_t)mobj->state];
        if(count==capacity){
            size_t nextCapacity=capacity?capacity*2:256;
            mobj_t **grown;
            if(nextCapacity>1048576)I_Error("Too many saved actors");
            grown=realloc(objects,nextCapacity*sizeof(*objects));
            if(!grown)I_Error("Out of memory restoring actor references");
            objects=grown;capacity=nextCapacity;
        }
        objects[count++]=mobj;
	    if (mobj->player)
	    {
		mobj->player = &players[(uintptr_t)mobj->player-1];
		mobj->player->mo = mobj;
	    }
	    P_SetThingPosition (mobj);
	    mobj->info = &mobjinfo[mobj->type];
	    mobj->floorz = mobj->subsector->sector->floorheight;
	    mobj->ceilingz = mobj->subsector->sector->ceilingheight;
	    mobj->thinker.function.acp1 = (actionf_p1)P_MobjThinker;
	    P_AddThinker (&mobj->thinker);
	    break;
			
	  default:
	    I_Error ("Unknown tclass %i in savegame after %u actors (record %u bytes)",tclass,(unsigned)count,(unsigned)sizeof(mobj_t));
	}
	
    }

}


