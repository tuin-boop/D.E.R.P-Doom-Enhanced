// Pads save_p to a 4-byte boundary
//  so that the load/save works on SGI&Gecko.
/* The native struct format is still host-specific (see BUILDING.md). */
#define SAVE_ALIGNMENT ((uintptr_t)_Alignof(max_align_t))
#define PADSAVEP() save_p += (SAVE_ALIGNMENT - ((uintptr_t)save_p & (SAVE_ALIGNMENT - 1))) & (SAVE_ALIGNMENT - 1)

/* Conservative bound, including the header, markers and alignment padding.
 * A thinker is saved at most once, as either a mobj or a special. */
size_t P_SaveGameBufferSize(void)
{
    const size_t records[] = {sizeof(mobj_t), sizeof(ceiling_t),
        sizeof(vldoor_t), sizeof(floormove_t), sizeof(plat_t),
        sizeof(lightflash_t), sizeof(strobe_t), sizeof(glow_t)};
    size_t largest = 0;
    for (size_t i = 0; i < sizeof(records) / sizeof(records[0]); ++i)
        if (records[i] > largest) largest = records[i];
    size_t size = 64 + MAXPLAYERS * (sizeof(player_t) + SAVE_ALIGNMENT);
    size += (size_t)numsectors * 7 * sizeof(short);
    size += (size_t)numlines * (3 + 2 * 5) * sizeof(short);
    for (thinker_t *th = thinkercap.next; th != &thinkercap; th = th->next)
    {
        if (size > INT_MAX - (largest + SAVE_ALIGNMENT + 1))
            I_Error("Savegame is too large");
        size += largest + SAVE_ALIGNMENT + 1;
    }
    if (size > INT_MAX) I_Error("Savegame is too large");
    return size;
}



//
// P_ArchivePlayers
//
void P_ArchivePlayers (void)
{
    int		i;
    int		j;
    player_t*	dest;
		
    for (i=0 ; i<MAXPLAYERS ; i++)
    {
	if (!playeringame[i])
	    continue;
	
	PADSAVEP();

	dest = (player_t *)save_p;
	memcpy (dest,&players[i],sizeof(player_t));
	save_p += sizeof(player_t);
	for (j=0 ; j<NUMPSPRITES ; j++)
	{
	    if (dest->psprites[j].state)
	    {
		dest->psprites[j].state 
		    = (state_t *)(uintptr_t)(dest->psprites[j].state-states);
	    }
	}
    }
}



//
// P_UnArchivePlayers
//
void P_UnArchivePlayers (void)
{
    int		i;
    int		j;
	
    for (i=0 ; i<MAXPLAYERS ; i++)
    {
	if (!playeringame[i])
	    continue;
	
	PADSAVEP();

	memcpy (&players[i],save_p, sizeof(player_t));
	save_p += sizeof(player_t);
	
	// will be set when unarc thinker
	players[i].mo = NULL;	
	players[i].message = NULL;
	players[i].attacker = NULL;

	for (j=0 ; j<NUMPSPRITES ; j++)
	{
	    if (players[i]. psprites[j].state)
	    {
		players[i]. psprites[j].state 
		    = &states[ (uintptr_t)players[i].psprites[j].state ];
	    }
	}
    }
}


//
// P_ArchiveWorld
//
void P_ArchiveWorld (void)
{
    int			i;
    int			j;
    sector_t*		sec;
    line_t*		li;
    side_t*		si;
    short*		put;
	
    put = (short *)save_p;
    
    // do sectors
    for (i=0, sec = sectors ; i<numsectors ; i++,sec++)
    {
	*put++ = sec->floorheight >> FRACBITS;
	*put++ = sec->ceilingheight >> FRACBITS;
	*put++ = sec->floorpic;
	*put++ = sec->ceilingpic;
	*put++ = sec->lightlevel;
	*put++ = sec->special;		// needed?
	*put++ = sec->tag;		// needed?
    }

    
    // do lines
    for (i=0, li = lines ; i<numlines ; i++,li++)
    {
	*put++ = li->flags;
	*put++ = li->special;
	*put++ = li->tag;
	for (j=0 ; j<2 ; j++)
	{
	    if (li->sidenum[j] == -1)
		continue;
	    
	    si = &sides[li->sidenum[j]];

	    *put++ = si->textureoffset >> FRACBITS;
	    *put++ = si->rowoffset >> FRACBITS;
	    *put++ = si->toptexture;
	    *put++ = si->bottomtexture;
	    *put++ = si->midtexture;	
	}
    }
	
    save_p = (byte *)put;
}



