"""Compile the preserved FluidWeapons/base-engine grayscale masks.
Their luminance is coverage (black is transparent), not a solid PNG alpha.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
names = ['chip1','chip2','chip3','chip4','chip5','scorch1','plasma1','plasma2',
         'bfgscrc1','bfgscrc2','bfglite1','bfglite2','NSHSB0','NSHSF0']
parts = ['// Generated by tools/build_fluid_effect_masks.py; see assets/fluid-effects/credits.txt.\n',
         'struct FluidMask {int w,h;const unsigned char *alpha;};\n']
for name in names:
    im = Image.open(root/'assets/fluid-effects'/f'{name}.png').convert('RGBA')
    alpha = [p[3]*max(p[:3])//255 for p in im.getdata()]
    assert min(alpha) == 0 and max(alpha) > 0, name
    parts.append(f'static const unsigned char fluid_{name}[]={{'+','.join(map(str,alpha))+'};\n')
    parts.append(f'static const FluidMask mask_{name}={{{im.width},{im.height},fluid_{name}}};\n')
parts.append('static const FluidMask fluidMasks[]={'+','.join('mask_'+n for n in names)+'};\n')
(root/'platform/scene3d/fluid_effect_assets.inc').write_text(''.join(parts))
